// Regenerates sdk/packages/core/src/abi.ts from the Foundry artifacts. Run after changing a contract:
//   (cd sdk/contracts && forge build) && node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const abiOf = (name) => JSON.parse(readFileSync(`sdk/contracts/out/${name}.sol/${name}.json`, 'utf8')).abi
const pp = abiOf('PaymentProcessor')
const sm = abiOf('SubscriptionManager')
writeFileSync(
  'sdk/packages/core/src/abi.ts',
  `// GENERATED by scripts/gen-abi.mjs from sdk/contracts. Do not edit.
/** ABI of the Sableye PaymentProcessor contract. */
export const paymentProcessorAbi = ${JSON.stringify(pp, null, 2)} as const

/** ABI of the Sableye SubscriptionManager contract. */
export const subscriptionManagerAbi = ${JSON.stringify(sm, null, 2)} as const
`,
)
console.log(`abi.ts: PaymentProcessor ${pp.length}, SubscriptionManager ${sm.length} entries`)
