// Regenerates sdk/packages/core/src/abi.ts from the Foundry artifact. Run after changing the contract:
//   (cd sdk/contracts && forge build) && node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const { abi } = JSON.parse(readFileSync('sdk/contracts/out/PaymentProcessor.sol/PaymentProcessor.json', 'utf8'))
writeFileSync(
  'sdk/packages/core/src/abi.ts',
  `// GENERATED by scripts/gen-abi.mjs from sdk/contracts. Do not edit.\n/** ABI of the Sableye PaymentProcessor contract. */\nexport const paymentProcessorAbi = ${JSON.stringify(abi, null, 2)} as const\n`,
)
console.log(`abi.ts: ${abi.length} entries`)
